-- H2 test database schema for ESTT tests

CREATE TABLE IF NOT EXISTS FIMS_FLIGHTSEASON (
    SEASON_REC_ID BIGINT PRIMARY KEY,
    SEASON_NAME VARCHAR(255),
    START_DATE DATE,
    END_DATE DATE,
    ACTIVESEASON_FLAG INTEGER
);

CREATE TABLE IF NOT EXISTS FIMS_FLIGHTSCHD_SEASON (
    FLIGHT_NUMBER VARCHAR(20),
    OPERATION_DAYS VARCHAR(20),
    FLYING_TIME BIGINT,
    START_DATE DATE,
    SEASON_REC_ID BIGINT,
    ARRI_OR_DEPT CHAR(1)
);

CREATE TABLE IF NOT EXISTS FIMS_FLIGHTSCHD_HST (
    FLIGHT_NUMBER VARCHAR(20),
    FLIGHT_DATE DATE,
    PRE_DEPT_DATETIME_ACTUAL TIMESTAMP,
    ACTUAL_DATETIME TIMESTAMP,
    SCHEDULED_DATETIME TIMESTAMP,
    ARRI_OR_DEPT CHAR(1)
);

